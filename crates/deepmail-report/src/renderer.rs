fn write_ioc_section(html: &mut String, ioc: &crate::assembler::IocAnalysisData) {
    let score: f32 = if ioc.malicious_count > 0 { 0.9 } else if ioc.suspicious_count > 0 { 0.6 } else { 0.1 };
    let _ = write!(
        html,
        r#"<details{open}><summary>IOC Analysis</summary><div class="card"><div class="card-body"><table>
<tr><td>Total IOCs</td><td>{total}</td></tr>
<tr><td>Malicious</td><td><span class="tag-malicious">{mal}</span></td></tr>
<tr><td>Suspicious</td><td><span class="tag-suspicious">{sus}</span></td></tr>"#,
        open = detail_open(score),
        total = ioc.total_iocs,
        mal = ioc.malicious_count,
        sus = ioc.suspicious_count,
    );

    if let Some(ref name) = ioc.campaign_name {
        let _ = write!(
            html,
            "<tr><td>Campaign</td><td>{} ({})</td></tr>",
            esc(name),
            esc(ioc.campaign_status.as_deref().unwrap_or("UNKNOWN")),
        );
    }

    let _ = write!(html, "</table>");

    if !ioc.top_iocs.is_empty() {
        let _ = write!(
            html,
            r#"<table style="margin-top:8px"><tr><th>Type</th><th>Value</th><th>Threat</th><th>Score</th></tr>"#
        );
        for t in &ioc.top_iocs {
            let _ = write!(
                html,
                r#"<tr><td>{}</td><td class="truncate">{}</td><td class="{}">{}</td><td>{}</td></tr>"#,
                esc(&t.ioc_type),
                truncate_url(&t.value, 80),
                threat_tag(&t.threat_level),
                esc(&t.threat_level),
                score_bar(t.score),
            );
        }
        let _ = write!(html, "</table>");
    }

    let _ = write!(html, "</div></div></details>\n");
}

