fn esc(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#x27;")
}

fn score_bar(score: f32) -> String {
    let pct = (score * 100.0).clamp(0.0, 100.0);
    let class = if pct < 30.0 {
        "bar-low"
    } else if pct < 60.0 {
        "bar-med"
    } else {
        "bar-high"
    };
    format!(
        r#"<span class="bar-wrap"><span class="bar {class}" style="width:{pct:.0}%"></span></span> {score:.2}"#,
        class = class,
        pct = pct,
        score = score,
    )
}

fn truncate_url(url: &str, max: usize) -> String {
    if url.len() <= max {
        esc(url)
    } else {
        let mut s = esc(&url[..max]);
        s.push_str("&hellip;");
        s
    }
}

fn threat_tag(level: &str) -> &'static str {
    match level {
        "CLEAN" => "tag-clean",
        "SUSPICIOUS" | "LOW_RISK" => "tag-suspicious",
        "MALICIOUS" | "PHISHING" => "tag-malicious",
        _ => "tag-unknown",
    }
}

fn detail_open(score: f32) -> &'static str {
    if score > 0.5 { " open" } else { "" }
}

fn write_verdict_card(html: &mut String, report: &ReportData, color: &str) {
    let _ = write!(
        html,
        r#"<div class="card"><div class="card-head">Verdict<span class="badge" style="background:{color}">{verdict}</span></div>
<div class="card-body"><table>
<tr><td>Final Score</td><td>{bar}</td></tr>
<tr><td>Signals Available</td><td>{signals}</td></tr>
</table></div></div>
"#,
        color = color,
        verdict = esc(&report.final_verdict),
        bar = score_bar(report.final_score),
        signals = report.signals_available,
    );
}

fn write_metadata_card(html: &mut String, report: &ReportData) {
    let m = &report.email_metadata;
    let _ = write!(html, r#"<div class="card"><div class="card-head">Email Metadata</div><div class="card-body"><table>"#);
    if let Some(ref v) = m.subject {
        let _ = write!(html, "<tr><td>Subject</td><td>{}</td></tr>", esc(v));
    }
    if let Some(ref v) = m.from {
        let _ = write!(html, "<tr><td>From</td><td>{}</td></tr>", esc(v));
    }
    if let Some(ref v) = m.date_sent {
        let _ = write!(html, "<tr><td>Date</td><td>{}</td></tr>", v.format("%Y-%m-%d %H:%M:%S UTC"));
    }
    if let Some(ref v) = m.message_id {
        let _ = write!(html, "<tr><td>Message-ID</td><td>{}</td></tr>", esc(v));
    }
    if let Some(ref v) = m.reply_to {
        let _ = write!(html, "<tr><td>Reply-To</td><td>{}</td></tr>", esc(v));
    }
    if let Some(ref v) = m.return_path {
        let _ = write!(html, "<tr><td>Return-Path</td><td>{}</td></tr>", esc(v));
    }
    let _ = write!(html, "</table></div></div>\n");
}

fn write_signal_table(html: &mut String, report: &ReportData) {
    let _ = write!(
        html,
        r#"<div class="card"><div class="card-head">Signal Breakdown</div><div class="card-body"><table>
<tr><th>Signal</th><th>Score</th></tr>"#,
    );

    let signals: Vec<(&str, Option<f32>)> = vec![
        ("Header", report.header_analysis.as_ref().map(|_| section_score(report, "header"))),
        ("DKIM", report.dkim_analysis.as_ref().map(|d| d.replay_confidence)),
        ("Geo", report.geo_analysis.as_ref().map(|_| section_score(report, "geo"))),
        ("IP", report.ip_analysis.as_ref().map(|ip| ip.max_threat_score)),
        ("Intel", report.intel_enrichment.as_ref().map(|i| i.max_vt_score)),
        ("IOC", report.ioc_analysis.as_ref().map(|_| section_score(report, "ioc"))),
        ("Homograph", report.homograph_analysis.as_ref().map(|_| section_score(report, "homograph"))),
        ("Body", report.body_analysis.as_ref().map(|b| b.final_phishing_score)),
        ("Sandbox URL", report.sandbox_url.as_ref().map(|_| section_score(report, "sandbox_url"))),
        ("Sandbox File", report.sandbox_file.as_ref().map(|_| section_score(report, "sandbox_file"))),
        ("Sandbox Dynamic", report.sandbox_dynamic.as_ref().map(|_| section_score(report, "sandbox_dynamic"))),
    ];

    for (name, score) in signals {
        match score {
            Some(s) => {
                let _ = write!(html, "<tr><td>{}</td><td>{}</td></tr>", name, score_bar(s));
            }
            None => {
                let _ = write!(html, "<tr><td>{}</td><td style=\"color:#95a5a6\">N/A</td></tr>", name);
            }
        }
    }

    let _ = write!(html, "</table></div></div>\n");
}

fn section_score(_report: &ReportData, _name: &str) -> f32 {
    0.0
}

fn write_header_section(html: &mut String, h: &crate::assembler::HeaderAnalysisData) {
    let score = if h.return_path_mismatch || h.reply_to_mismatch { 0.7 } else { 0.2 };
    let _ = write!(
        html,
        r#"<details{open}><summary>Header Analysis</summary><div class="card"><div class="card-body"><table>
<tr><td>SPF</td><td>{spf}</td></tr>
<tr><td>DKIM</td><td>{dkim}</td></tr>
<tr><td>DMARC</td><td>{dmarc}</td></tr>
<tr><td>Return-Path Mismatch</td><td>{rp}</td></tr>
<tr><td>Reply-To Mismatch</td><td>{rt}</td></tr>
<tr><td>Hop Count</td><td>{hops}</td></tr>
</table>"#,
        open = detail_open(score),
        spf = esc(h.spf_result.as_deref().unwrap_or("N/A")),
        dkim = esc(h.dkim_result.as_deref().unwrap_or("N/A")),
        dmarc = esc(h.dmarc_result.as_deref().unwrap_or("N/A")),
        rp = if h.return_path_mismatch { "Yes" } else { "No" },
        rt = if h.reply_to_mismatch { "Yes" } else { "No" },
        hops = h.hop_count,
    );

    if !h.findings.is_empty() {
        let _ = write!(html, "<h4 style=\"margin:12px 0 4px\">Findings</h4><ul>");
        for f in &h.findings {
            let _ = write!(html, "<li>{}</li>", esc(f));
        }
        let _ = write!(html, "</ul>");
    }

    let _ = write!(html, "</div></div></details>\n");
}

fn write_dkim_section(html: &mut String, d: &crate::assembler::DkimAnalysisData) {
    let _ = write!(
        html,
        r#"<details{open}><summary>DKIM Analysis</summary><div class="card"><div class="card-body"><table>
<tr><td>Replay Confidence</td><td>{bar}</td></tr>
<tr><td>Verdict</td><td>{verdict}</td></tr>
</table>"#,
        open = detail_open(d.replay_confidence),
        bar = score_bar(d.replay_confidence),
        verdict = esc(&d.verdict),
    );

    if !d.signatures.is_empty() {
        let _ = write!(html, r#"<table style="margin-top:8px"><tr><th>Selector</th><th>Domain</th><th>Body Hash</th></tr>"#);
        for sig in &d.signatures {
            let _ = write!(
                html,
                "<tr><td>{}</td><td>{}</td><td>{}</td></tr>",
                esc(&sig.selector),
                esc(&sig.domain),
                if sig.body_hash_match { "Match" } else { "Mismatch" }
            );
        }
        let _ = write!(html, "</table>");
    }

    let _ = write!(html, "</div></div></details>\n");
}

fn write_geo_section(html: &mut String, g: &crate::assembler::GeoAnalysisData) {
    let score: f32 = match g.overall_risk.as_str() {
        "HIGH" | "CRITICAL" => 0.8,
        "MEDIUM" => 0.5,
        _ => 0.2,
    };
    let _ = write!(
        html,
        r#"<details{open}><summary>Geo Analysis</summary><div class="card"><div class="card-body"><table>
<tr><td>Origin IP</td><td>{ip}</td></tr>
<tr><td>Origin Country</td><td>{country}</td></tr>
<tr><td>Overall Risk</td><td>{risk}</td></tr>
</table>"#,
        open = detail_open(score),
        ip = esc(g.origin_ip.as_deref().unwrap_or("N/A")),
        country = esc(g.origin_country.as_deref().unwrap_or("N/A")),
        risk = esc(&g.overall_risk),
    );

    if !g.hops.is_empty() {
        let _ = write!(html, r#"<table style="margin-top:8px"><tr><th>IP</th><th>Country</th><th>Tor</th><th>VPN</th></tr>"#);
        for hop in &g.hops {
            let _ = write!(
                html,
                "<tr><td>{}</td><td>{}</td><td>{}</td><td>{}</td></tr>",
                esc(&hop.ip),
                esc(hop.country.as_deref().unwrap_or("N/A")),
                if hop.is_tor { "Yes" } else { "No" },
                if hop.is_vpn { "Yes" } else { "No" },
            );
        }
        let _ = write!(html, "</table>");
    }

    let _ = write!(html, "</div></div></details>\n");
}

