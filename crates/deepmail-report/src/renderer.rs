use crate::assembler::ReportData;
use crate::error::ReportError;
use std::fmt::Write;

pub fn render_json(report: &ReportData) -> Result<Vec<u8>, ReportError> {
    serde_json::to_vec_pretty(report).map_err(|e| ReportError::RenderError(e.to_string()))
}

